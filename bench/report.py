"""Build the results summary from raw run output.

    python -m bench.report            # writes results/SUMMARY.md

Every number in the summary comes from `results/raw/`. Nothing is hand-entered,
which is the point: the README's results table is reproducible by running the
harness, and a claim that is not in the raw output cannot appear in the summary.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
from typing import Any

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW_DIR = os.path.join(REPO_ROOT, "results", "raw")
OUT_PATH = os.path.join(REPO_ROOT, "results", "SUMMARY.md")

# Published figures from VectifyAI/PageIndex-OSS-Benchmark, cited as an external
# comparison point. That repository grants no licence, so its numbers are
# referenced here rather than its files. Verified against results.json upstream.
PUBLISHED = [
    ("gpt-5.6-luna", "none", 0.8548, 0.003081),
    ("gpt-5.6-luna", "medium", 0.9194, 0.003806),
    ("gpt-5.6-luna", "high", 0.9677, 0.003607),
    ("gpt-5.6-terra", "medium", 0.9839, 0.030322),
    ("gpt-5.6-sol", "medium", 1.0, 0.081008),
]


def load_runs() -> list[dict]:
    runs = []
    for path in sorted(glob.glob(os.path.join(RAW_DIR, "*.json"))):
        with open(path) as fh:
            payload = json.load(fh)
        payload["_path"] = os.path.relpath(path, REPO_ROOT)
        runs.append(payload)
    return runs


def fmt(value: Any, spec: str = ".3f", dash: str = "—") -> str:
    return dash if value is None else format(value, spec)


def pct(value: Any) -> str:
    return "—" if value is None else f"{value * 100:.1f}%"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="bench.report", description=__doc__)
    ap.parse_args(argv)

    runs = load_runs()
    lines: list[str] = []
    add = lines.append

    add("# Results")
    add("")
    add(
        "Generated by `python -m bench.report` from `results/raw/`. "
        "Every figure below is a direct aggregate of recorded per-question output; "
        "nothing is hand-entered."
    )
    add("")

    if not runs:
        add("No runs recorded yet. Produce some with:")
        add("")
        add("```bash")
        add("python -m bench.run --system pageindex_local --set comparable_90")
        add("python -m bench.run --system pgvector_baseline --set comparable_90")
        add("```")
    else:
        add("## Headline")
        add("")
        add(
            "| System | Set | n | Accuracy | 95% CI | Retrieval hit rate | "
            "p50 latency | p95 latency | Cost/question |"
        )
        add("| --- | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: |")
        for run in runs:
            s = run.get("summary") or {}
            ci = s.get("accuracy_ci95")
            lat = s.get("latency") or {}
            cost = s.get("cost_usd") or {}
            add(
                f"| `{run['system']}` | `{run.get('set')}` | {s.get('n_scored', 0)} "
                f"| {fmt(s.get('accuracy'))} "
                f"| {'—' if not ci else f'{ci[0]:.3f}–{ci[1]:.3f}'} "
                f"| {pct(s.get('retrieval_hit_rate'))} "
                f"| {fmt(lat.get('p50_s'), '.2f')}s "
                f"| {fmt(lat.get('p95_s'), '.2f')}s "
                f"| ${fmt(cost.get('mean_per_question'), '.5f')} |"
            )
        add("")
        add(
            "Accuracy is the fraction of scored questions the judge accepted. "
            "Retrieval hit rate is the fraction where at least one annotated evidence page "
            "was actually retrieved — the metric that isolates retrieval from generation, "
            "since the chat model and judge are identical across systems."
        )
        add("")
        add("## Run detail")
        add("")
        for run in runs:
            s = run.get("summary") or {}
            lat = s.get("latency") or {}
            add(f"### `{run['system']}` on `{run.get('set')}`")
            add("")
            add(f"- Raw output: `{run['_path']}`")
            add(f"- Questions scored: {s.get('n_scored')} of {s.get('n_total')} "
                f"({s.get('n_errors')} error(s))")
            add(f"- Documents: {run.get('n_documents')}")
            add(f"- Judge model: `{run.get('judge_model')}` "
                f"(identical across systems: {len({r.get('judge_model') for r in runs}) == 1})")
            add(f"- Chat/index models: {json.dumps(run.get('config', {}))}")
            add(f"- Latency: p50 {fmt(lat.get('p50_s'), '.2f')}s, "
                f"p95 {fmt(lat.get('p95_s'), '.2f')}s, mean {fmt(lat.get('mean_s'), '.2f')}s")
            tokens = s.get("tokens") or {}
            add(f"- Tokens: {tokens.get('prompt', 0):,} prompt, "
                f"{tokens.get('completion', 0):,} completion")
            add(f"- Mean context size: {fmt(s.get('context_chars_mean'), ',.0f')} chars")
            add(f"- Started: {run.get('started_at')}  |  Updated: {run.get('updated_at')}")
            add("")

        add("## External comparison point")
        add("")
        add(
            "Published PageIndex OSS figures, from "
            "`VectifyAI/PageIndex-OSS-Benchmark` (62 questions, 34 documents). That repository "
            "grants no licence, so no file from it is reproduced here — only these numbers are "
            "cited. It varies the chat model and never measures a vector-RAG baseline, which is "
            "the gap this harness exists to fill."
        )
        add("")
        add("| Chat model | Reasoning effort | Accuracy | Cost/question |")
        add("| --- | --- | ---: | ---: |")
        for model, effort, acc, cost in PUBLISHED:
            add(f"| `{model}` | {effort} | {acc * 100:.1f}% | ${cost:.5f} |")
        add("")

    add("## Known limitations")
    add("")
    add(
        "- The vector baseline is the naïve chunk-and-embed implementation, not hybrid search "
        "with a reranker. See `docs/DECISIONS.md`."
    )
    add(
        "- The baseline answers single-shot while PageIndex answers agentically. The asymmetry "
        "favours PageIndex and is disclosed rather than buried."
    )
    add(
        "- With n≈90 the 95% CI on accuracy is roughly ±7 points. Differences inside the "
        "interval are not claimed as wins."
    )

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT_PATH} ({len(runs)} run(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
